const difficultyLabels = { Easy: "简单", Medium: "中等", Hard: "困难" };
const difficultyLevels = { Easy: "easy", Medium: "medium", Hard: "hard" };

export function problemIdFromTitle(title) {
	const match = /^(\d+)\./.exec(String(title).trim());
	return match ? match[1] : null;
}

export function problemBadges(title) {
	const id = problemIdFromTitle(title);
	const info = id ? problemMeta[id] : null;
	if (!info) return "";
	const level = difficultyLevels[info.difficulty] ?? "medium";
	const difficulty = `<span class="badge difficulty ${level}">${difficultyLabels[info.difficulty] ?? "中等"}</span>`;
	const topics = info.topics
		.filter((slug) => topicLabels[slug])
		.map((slug) => `<span class="badge topic" data-topic="${slug}">${topicLabels[slug]}</span>`)
		.join("");
	return difficulty + topics;
}
