const commentPrefix = (language) => (language === "python" ? "#" : "//");

export function decorateCodes(id, codes = []) {
	const key = String(id).match(/^\s*(\d+)/)?.[1] ?? String(id);
	const idea = codeIdeas[key];
	if (!idea) return codes;
	return codes.map((code) => ({
		...code,
		source: `${commentPrefix(code.id)} ${idea}\n${code.source}`,
		lines: Object.fromEntries(
			Object.entries(code.lines ?? {}).map(([stage, line]) => [
				stage,
				typeof line === "number" ? line + 1 : line,
			]),
		),
	}));
}
